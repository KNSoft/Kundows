param(
    [Parameter(Mandatory = $true)]
    [string]$SourceRoot,
    [Parameter(Mandatory = $true)]
    [string]$GeneratedRoot,
    [Parameter(Mandatory = $true)]
    [string]$CMakeListFile,
    [Parameter(Mandatory = $true)]
    [string]$SourceDirectory,
    [string]$OutputDirectory = "",
    [string]$Compiler = "",
    [string]$Assembler = ""
)

$ErrorActionPreference = "Stop"

function Expand-CMakeValue([string]$Value, [hashtable]$Variables) {
    for ($pass = 0; $pass -lt 8; $pass++) {
        $expanded = [regex]::Replace($Value, "\$\{(?<name>[A-Za-z_][A-Za-z0-9_]*)\}", {
            param($match)
            $name = $match.Groups["name"].Value
            if ($Variables.ContainsKey($name)) { return $Variables[$name] }
            return $match.Value
        })
        if ($expanded -eq $Value) { break }
        $Value = $expanded
    }
    return $Value
}

function Resolve-CMakePath([string]$Value, [string]$BaseDirectory) {
    $value = $Value.Trim().Trim('"', "'")
    if (-not $value -or $value -match '\$<') {
        return $null
    }
    if ([IO.Path]::IsPathRooted($value)) {
        return [IO.Path]::GetFullPath($value)
    }
    return [IO.Path]::GetFullPath((Join-Path $BaseDirectory $value))
}

function Write-Bin2c([string]$InputFile, [string]$CFile, [string]$HeaderFile, [string]$Format, [string]$ArrayName) {
    if (-not (Test-Path -LiteralPath $InputFile -PathType Leaf)) {
        throw "bin2c input was not found: $InputFile"
    }
    $bytes = [IO.File]::ReadAllBytes($InputFile)
    $includeName = [IO.Path]::GetFileName($HeaderFile)
    $c = New-Object System.Text.StringBuilder
    [void]$c.AppendLine("/* This file is autogenerated, do not edit. */")
    [void]$c.AppendLine()
    [void]$c.AppendLine("#include `"$includeName`"")
    [void]$c.AppendLine()
    [void]$c.AppendLine("unsigned char $ArrayName[] =")
    [void]$c.AppendLine("{")
    for ($index = 0; $index -lt $bytes.Length; $index += 16) {
        $end = [Math]::Min($index + 16, $bytes.Length)
        $values = for ($offset = $index; $offset -lt $end; $offset++) {
            "0x{0:x2}" -f $bytes[$offset]
        }
        [void]$c.AppendLine("   " + (($values -join ", ") + ","))
    }
    [void]$c.AppendLine("};")

    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $CFile) | Out-Null
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $HeaderFile) | Out-Null
    [IO.File]::WriteAllText($CFile, $c.ToString(), [Text.UTF8Encoding]::new($false))
    $header = @(
        "/* This file is autogenerated, do not edit. */"
        ""
        "#define ${ArrayName}_SIZE $($bytes.Length)"
        "extern unsigned char ${ArrayName}[$($bytes.Length)];"
        ""
    ) -join "`r`n"
    [IO.File]::WriteAllText($HeaderFile, $header, [Text.UTF8Encoding]::new($false))
}

$resolvedSourceRoot = [IO.Path]::GetFullPath($SourceRoot)
$resolvedSourceDirectory = [IO.Path]::GetFullPath($SourceDirectory)
if (-not $OutputDirectory) {
    $relativeDirectory = [IO.Path]::GetRelativePath($resolvedSourceRoot, $resolvedSourceDirectory)
    $OutputDirectory = Join-Path $GeneratedRoot $relativeDirectory
}
$resolvedOutputDirectory = [IO.Path]::GetFullPath($OutputDirectory)

$variables = @{
    "REACTOS_SOURCE_DIR" = $resolvedSourceRoot
    "CMAKE_CURRENT_SOURCE_DIR" = $resolvedSourceDirectory
    "CMAKE_CURRENT_BINARY_DIR" = $resolvedOutputDirectory
}
$contents = Get-Content -LiteralPath $CMakeListFile -Raw
foreach ($match in [regex]::Matches($contents, "(?is)set\s*\(\s*(?<name>[A-Za-z_][A-Za-z0-9_]*)\s+(?<value>.*?)\)")) {
    $variables[$match.Groups["name"].Value] = $match.Groups["value"].Value.Trim()
}

foreach ($match in [regex]::Matches($contents, "(?im)native-bin2c\s+(?<body>[^\r\n\)]*)")) {
    $tokens = @(
        (Expand-CMakeValue $match.Groups["body"].Value $variables) -split "\s+" |
            ForEach-Object { $_.Trim() } |
            Where-Object { $_ }
    )
    if ($tokens.Count -lt 5) {
        continue
    }
    $inputFile = Resolve-CMakePath $tokens[0] $resolvedSourceDirectory
    if (-not $inputFile -and $tokens[0] -match '^\$<TARGET_PROPERTY:(?<target>[^,]+),BINARY_PATH>$') {
        if (-not $Compiler -or -not $Assembler) {
            throw "Resolving '$($tokens[0])' requires the MSVC compiler and x86 assembler."
        }
        $targetName = $Matches["target"]
        $targetCMake = Get-ChildItem -LiteralPath $resolvedSourceRoot -Recurse -Filter CMakeLists.txt -File |
            Where-Object {
                $text = Get-Content -LiteralPath $_.FullName -Raw
                $text -match ("(?is)add_asm16_bin\s*\(\s*" + [regex]::Escape($targetName) + "\b")
            } |
            Select-Object -First 1
        if ($null -eq $targetCMake) {
            throw "Unable to locate the CMake definition for target '$targetName'."
        }
        & (Join-Path $PSScriptRoot 'GenerateReactOSAsm16.ps1') `
            -SourceRoot $resolvedSourceRoot `
            -GeneratedRoot $GeneratedRoot `
            -CMakeListFile $targetCMake.FullName `
            -SourceDirectory $targetCMake.DirectoryName `
            -Compiler $Compiler `
            -Assembler $Assembler
        if ($LASTEXITCODE -ne 0) {
            throw "16-bit assembly generation failed for target '$targetName'."
        }
        $targetRelativeDirectory = [IO.Path]::GetRelativePath(
            $resolvedSourceRoot,
            $targetCMake.DirectoryName)
        $targetContents = Get-Content -LiteralPath $targetCMake.FullName -Raw
        $targetMatch = [regex]::Match(
            $targetContents,
            "(?is)add_asm16_bin\s*\(\s*" + [regex]::Escape($targetName) + "\s+(?<output>[^\s\)]+)")
        if (-not $targetMatch.Success) {
            throw "Unable to resolve the binary output for target '$targetName'."
        }
        $targetVariables = @{
            "CMAKE_CURRENT_BINARY_DIR" = (Join-Path $GeneratedRoot $targetRelativeDirectory)
        }
        $targetOutputValue = Expand-CMakeValue $targetMatch.Groups["output"].Value $targetVariables
        $inputFile = Resolve-CMakePath $targetOutputValue (Join-Path $GeneratedRoot $targetRelativeDirectory)
    }
    $cFile = Resolve-CMakePath $tokens[1] $resolvedOutputDirectory
    $headerFile = Resolve-CMakePath $tokens[2] $resolvedOutputDirectory
    $format = $tokens[3]
    $arrayName = $tokens[4]
    if ($inputFile -and $cFile -and $headerFile) {
        Write-Bin2c $inputFile $cFile $headerFile $format $arrayName
    }
}
