param(
    [Parameter(Mandatory = $true)]
    [string]$WidlTool,
    [Parameter(Mandatory = $true)]
    [string]$IdlFile,
    [Parameter(Mandatory = $true)]
    [string]$OutputFile,
    [Parameter(Mandatory = $true)]
    [ValidateSet("Win32", "x64", "ARM64")]
    [string]$Architecture,
    [ValidateSet("Iids", "Header")]
    [string]$Mode = "Iids",
    [string]$IncludeDirectoryList = ""
)

$ErrorActionPreference = "Stop"
$IncludeDirectory = @(
    $IncludeDirectoryList -split ";" |
        ForEach-Object { $_.Trim() } |
        Where-Object { $_.Length -gt 0 }
)

function Convert-UuidToMidlParts([string]$UuidText) {
    $parts = $UuidText.Trim().Trim("{}") -split "-"
    if ($parts.Count -ne 5 -or $parts[3].Length -ne 4 -or $parts[4].Length -ne 12) {
        throw "Invalid UUID '$UuidText' in '$IdlFile'"
    }

    $tail = $parts[3] + $parts[4]
    $bytes = for ($i = 0; $i -lt $tail.Length; $i += 2) {
        "0x$($tail.Substring($i, 2).ToLowerInvariant())"
    }

    return @(
        "0x$($parts[0].ToLowerInvariant())",
        "0x$($parts[1].ToLowerInvariant())",
        "0x$($parts[2].ToLowerInvariant())"
    ) + $bytes
}

function Write-FallbackIids {
    $source = Get-Content -LiteralPath $IdlFile -Raw
    $source = [regex]::Replace($source, "(?s)/\*.*?\*/", "")
    $source = [regex]::Replace($source, "(?m)//.*$", "")

    $declarations = [regex]::Matches(
        $source,
        "(?is)\[(?<attributes>.*?)\]\s*(?<kind>interface|dispinterface|coclass|library)\s+(?<name>[A-Za-z_][A-Za-z0-9_]*)"
    )
    $definitions = New-Object System.Collections.Generic.List[string]

    foreach ($declaration in $declarations) {
        $uuidMatch = [regex]::Match(
            $declaration.Groups["attributes"].Value,
            "(?is)\buuid\s*\(\s*(?<uuid>[0-9a-f-]+)\s*\)"
        )
        if (-not $uuidMatch.Success) {
            continue
        }

        $kind = $declaration.Groups["kind"].Value.ToLowerInvariant()
        $name = $declaration.Groups["name"].Value
        $symbolPrefix = switch ($kind) {
            "interface" { "IID_" }
            "dispinterface" { "DIID_" }
            "coclass" { "CLSID_" }
            "library" { "LIBID_" }
        }
        $type = if ($kind -eq "coclass") { "CLSID" } else { "IID" }
        $parts = Convert-UuidToMidlParts $uuidMatch.Groups["uuid"].Value
        $definitions.Add(
            "MIDL_DEFINE_GUID($type, $symbolPrefix$name, $($parts -join ', '));"
        )
    }

    if ($definitions.Count -eq 0) {
        throw "WIDL failed and no UUID declarations were found in '$IdlFile'"
    }

    $header = @'
/*** Generated by the native WIDL MSBuild fallback from __IDL_FILE__ - Do not edit ***/

#ifdef __REACTOS__
#define WIN32_NO_STATUS
#define WIN32_LEAN_AND_MEAN
#endif

#include <rpc.h>
#include <rpcndr.h>

#ifdef _MIDL_USE_GUIDDEF_

#ifndef INITGUID
#define INITGUID
#include <guiddef.h>
#undef INITGUID
#else
#include <guiddef.h>
#endif

#define MIDL_DEFINE_GUID(type,name,l,w1,w2,b1,b2,b3,b4,b5,b6,b7,b8) \
    DEFINE_GUID(name,l,w1,w2,b1,b2,b3,b4,b5,b6,b7,b8)

#elif defined(__cplusplus)

#define MIDL_DEFINE_GUID(type,name,l,w1,w2,b1,b2,b3,b4,b5,b6,b7,b8) \
    EXTERN_C const type DECLSPEC_SELECTANY name = {l,w1,w2,{b1,b2,b3,b4,b5,b6,b7,b8}}

#else

#define MIDL_DEFINE_GUID(type,name,l,w1,w2,b1,b2,b3,b4,b5,b6,b7,b8) \
    const type DECLSPEC_SELECTANY name = {l,w1,w2,{b1,b2,b3,b4,b5,b6,b7,b8}}

#endif

#ifdef __cplusplus
extern "C" {
#endif

'@
    $header = $header.Replace("__IDL_FILE__", $IdlFile)

    $footer = @'

#ifdef __cplusplus
}
#endif

#undef MIDL_DEFINE_GUID
'@
    Set-Content -LiteralPath $OutputFile -Value ($header + ($definitions -join [Environment]::NewLine) + $footer) -Encoding utf8
}

if (-not (Test-Path -LiteralPath $WidlTool)) {
    throw "WIDL was not found: $WidlTool"
}

$outputDirectory = Split-Path -Parent $OutputFile
New-Item -ItemType Directory -Force -Path $outputDirectory | Out-Null

$arguments = @("-nostdinc", "-D__REACTOS__", "-D_MIDL_USE_GUIDDEF_")
switch ($Architecture) {
    "Win32" {
        $arguments += @("-m32", "--win32", "-b", "i386-x-y")
    }
    "x64" {
        $arguments += @("-m64", "--win64", "-b", "amd64-x-y")
    }
    "ARM64" {
        $arguments += @("-b", "arm64-x-y")
    }
}
foreach ($directory in $IncludeDirectory) {
    $arguments += "-I$directory"
}
if ($Mode -eq "Header") {
    $arguments += @("-Oicf", "-h")
} else {
    $arguments += @("-Os", "-u")
}
$arguments += @("-o", $OutputFile, $IdlFile)

$widlExitCode = 0
Push-Location -LiteralPath $outputDirectory
try {
    & $WidlTool @arguments
    $widlExitCode = $LASTEXITCODE
}
finally {
    Pop-Location
}

if ($widlExitCode -eq 0) {
    exit 0
}

if ($Mode -eq "Header") {
    throw "WIDL exited with code $widlExitCode while generating '$OutputFile'"
}
Write-Warning "WIDL exited with code $widlExitCode for '$IdlFile'; using the UUID-only fallback."
Write-FallbackIids
exit 0
